async def _record_on(db_session, user_id="user_test"):
    await _seed_user(db_session, user_id=user_id, email=f"{user_id}@example.org")
    db_session.add(DatasetSettings(user_id=user_id, recording_enabled=True))
    await db_session.commit()


async def _count(session_factory, model):
    async with session_factory() as s:
        return await s.scalar(select(func.count()).select_from(model))


