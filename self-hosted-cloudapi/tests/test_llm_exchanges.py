async def test_the_recorders_uploads_reconstruct_every_request_exactly(authed, db_session, session_factory):
    await _record_on(db_session)
    for item in FIXTURE["exchanges"]:
        if item["accepted"]:
            assert _post(authed, "/api/llm-exchanges", item["body"]).json()["stored"] is True
    for outcome in FIXTURE["outcomes"]:
        _post(authed, "/api/llm-exchanges/outcome", outcome)

    async with session_factory() as s:
        rebuilt = {e.id: e for e in await load_task(s, "user_test", "task-contract", verify_wire=True)}

    accepted = {item["body"]["id"] for item in FIXTURE["exchanges"] if item["accepted"]}
    assert set(rebuilt) == accepted
    for expected in FIXTURE["expected"]:
        if expected["id"] not in accepted:
            continue
        exchange = rebuilt[expected["id"]]
        assert exchange.complete, expected["id"]
        assert exchange.system == expected["system"]
        assert exchange.tools == expected["tools"]
        assert exchange.messages == expected["messages"]
        # The exact HTTP body, byte for byte: same JSON and the recorded hash matches.
        assert exchange.wire_body == json.loads(expected["wireBody"])
        assert exchange.wire_verified is True, expected["id"]
        assert exchange.wire["url"] == "https://llm.example/v1/chat/completions"

    by_sequence = {e.sequence: e for e in rebuilt.values()}
    assert by_sequence[0].issues == []
    assert by_sequence[1].issues == ["api_error"]
    assert by_sequence[2].issues == ["tool_failed"]
    assert by_sequence[4].issues == []
    # The lost fourth upload: the fifth exchange is a full snapshot, not a delta of it.
    assert by_sequence[4].base_id is None


async def test_a_missing_base_makes_the_chain_incomplete(authed, db_session, session_factory):
    await _record_on(db_session)
